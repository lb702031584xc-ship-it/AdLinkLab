function googleAccount(
  partial: Omit<GoogleAccount, "createdAt" | "updatedAt" | "googleCustomerId" | "descriptiveName" | "currencyCode" | "timeZone"> & {
    createdAt?: Date;
  }
): GoogleAccount {
  const at = partial.createdAt ?? FIXTURE_NOW;
  return {
    ...partial,
    googleCustomerId: partial.customerId,
    descriptiveName: partial.name,
    currencyCode: partial.currency,
    timeZone: partial.timezone,
    ...stamp(at),
  };
}

