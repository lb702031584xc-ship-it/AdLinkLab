export function countActiveUrlVersionsByEntity(
  versions: UrlVersion[]
): Map<string, number> {
  const map = new Map<string, number>();
  for (const v of versions) {
    if (v.status !== "ACTIVE") continue;
    const key = `${v.tenantId}:${v.entityType}:${v.entityId}`;
    map.set(key, (map.get(key) ?? 0) + 1);
  }
  return map;
}

