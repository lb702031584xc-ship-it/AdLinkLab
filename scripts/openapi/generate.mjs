#!/usr/bin/env node
/**
 * P2-4：OpenAPI 契约生成器。
 *
 * 启动 API（内存服务，无需数据库），用 `app.printRoutes()` 导出路由清单，
 * 生成最小 openapi.yaml（paths + methods）。
 *
 * 诚实说明：路由没有 Fastify schemas，所以本文件是“路由清单契约”，
 * 不是完整 schema（无 request/response body 定义）。不要把本文件当成
 * 完整 OpenAPI 契约；新增路由时必须重新生成并提交。
 *
 * 用法：node scripts/openapi/generate.mjs [--out <path>]
 * 要求：先构建 API（apps/api/dist 存在），见 scripts/openapi/ci-check.sh。
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");
const OUT = process.argv.includes("--out")
  ? resolve(process.argv[process.argv.indexOf("--out") + 1])
  : resolve(ROOT, "openapi.yaml");

// 路由注册在 `if (services.prisma)` 内；没有 DATABASE_URL 时 PrismaClient
// 不创建，大部分路由不会注册。生成器只做 printRoutes（不查库），
// 所以用一个假 DATABASE_URL 让 PrismaClient 懒构造即可（不建立真实连接）。
if (!process.env.DATABASE_URL) {
  process.env.DATABASE_URL = "postgresql://dummy:dummy@localhost:5432/dummy";
}

const { buildApp } = await import(resolve(ROOT, "apps/api/dist/app.js"));
const app = await buildApp();
const tree = app.printRoutes();
await app.close();

/**
 * 解析 Fastify printRoutes 的 radix 树。
 * 每行形如：`    ├── api/v1/ (GET, HEAD)` 或 `    │   └── :id (GET, HEAD)`。
 * 缩进每级 4 列；用栈按深度还原完整路径。
 */
function parseRoutes(text) {
  const paths = new Map(); // path -> Set(methods)
  const stack = []; // { depth, segment }
  for (const rawLine of text.split("\n")) {
    const line = rawLine.replace(/\s+$/, "");
    if (!line.trim()) continue;
    // 找到分支标记 ├── 或 └── 的位置 → 深度 = 位置 / 4。
    const marker = line.search(/[├└]── /);
    if (marker < 0) continue;
    const depth = Math.floor(marker / 4);
    const rest = line.slice(marker + 4);
    if (rest.startsWith("(empty root node)")) continue;
    const methodMatch = rest.match(/^(.*?)\s*\(([^)]+)\)\s*$/);
    const segment = (methodMatch ? methodMatch[1] : rest).trim();
    while (stack.length > depth) stack.pop();
    stack[depth] = segment;
    if (!methodMatch) continue;
    const methods = methodMatch[2]
      .split(",")
      .map((m) => m.trim().toUpperCase())
      .filter((m) => m && m !== "HEAD"); // HEAD 由 Fastify 为 GET 自动补齐，不单独列
    if (methods.length === 0) continue;
    // 拼路径：radix 树按字符压缩（如 ad-groups 拆成 a + d + -groups），
    // 各段直接拼接（斜杠已包含在段内，如 "api/v1/"、"/"），绝不额外加斜杠。
    let path = "";
    for (const seg of stack) {
      if (!seg) continue;
      path += seg;
    }
    if (!path) path = "/";
    else if (!path.startsWith("/")) path = "/" + path;
    if (!paths.has(path)) paths.set(path, new Set());
    for (const m of methods) paths.get(path).add(m);
  }
  return paths;
}

function yamlEscape(s) {
  return JSON.stringify(s);
}

const paths = parseRoutes(tree);
const sortedPaths = [...paths.keys()].sort();
const lines = [];
lines.push("# Auto-generated by scripts/openapi/generate.mjs — DO NOT EDIT BY HAND.");
lines.push("# Contract = route inventory (paths + methods). Routes carry no");
lines.push("# Fastify schemas, so there are no request/response body definitions.");
lines.push("openapi: 3.0.3");
lines.push("info:");
lines.push("  title: AdLinkLab API");
lines.push("  version: 1.0.0");
lines.push("paths:");
for (const p of sortedPaths) {
  lines.push(`  ${yamlEscape(p)}:`);
  for (const method of [...paths.get(p)].sort()) {
    const lower = method.toLowerCase();
    lines.push(`    ${lower}:`);
    lines.push(`      summary: ${yamlEscape(`Auto-generated route inventory: ${method} ${p}`)}`);
    lines.push("      responses:");
    lines.push("        '200':");
    lines.push("          description: OK");
  }
}
lines.push("");
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} (${sortedPaths.length} paths)`);
